def located_native_ms_maxima(q, layouts, sources):
    """Return one exact source witness, or no authority; never infer a value.

    ``_question_witness`` supplies only MS layouts, so QP ownership is bound by
    the exact source and full-page scope (and checked by its existing caller).
    Any change to the complete native MS body, words, boxes or starts rejects.
    """
    if not isinstance(q, dict) or type(q.get('number')) is not int:
        return []
    try:
        matches = [entry for entry in _WITNESSES
                   if entry['number'] == q['number']
                   and all(sources[role]['sha256'] == entry['sources'][role]['sha256']
                           for role in ('qp', 'ms'))]
        if len(matches) != 1:
            return []
        entry = matches[0]
        for field in ('qid', 'id'):
            if field in q and q[field] != entry['qid']:
                return []
        for role, field in (('qp', 'question_regions'), ('ms', 'scheme_regions')):
            source = sources[role]
            expected = entry['sources'][role]
            if (any(source.get(key) != value for key, value in expected.items())
                    or source_identity(source['path'], role, entry['exam']['course']) != entry['exam']
                    or 'exam' in source and source['exam'] != entry['exam']
                    or source.get('issues', [])):
                return []
            regions = [{'role': role, 'source_id': expected['asset_id'],
                        'source_sha256': expected['sha256'], 'page': page,
                        'box': [0, 0, 1, 1]} for page in entry[role + '_pages']]
            if q.get(field) != regions:
                return []
        if canonical_qid(entry['exam'], q['number']) != entry['qid']:
            return []
        native = layouts['ms']
        encoded = json.dumps(native, sort_keys=True, separators=(',', ':'), ensure_ascii=False).encode()
        if hashlib.sha256(encoded).hexdigest() != entry['ms_layout_sha256']:
            return []
        maximum = entry['maximum']
        region = maximum['region']
        words = native[region['page'] - 1]['words']
        tokens = maximum['tokens']
        if any(words.count(token) != 1 for token in tokens):
            return []
        box = [min(w['box'][0] for w in tokens), min(w['box'][1] for w in tokens),
               max(w['box'][2] for w in tokens), max(w['box'][3] for w in tokens)]
        if box != region['box']:
            return []
        contained = [word for word in words if box[0] <= word['box'][0]
                     and box[1] <= word['box'][1] and word['box'][2] <= box[2]
                     and word['box'][3] <= box[3]]
        literal = ' '.join(word['text'] for word in contained)
        if contained != tokens or literal != maximum['literal']:
            return []
        value = _whole_total(literal, 'ms', q['number'])
        if value <= 0 or value != maximum['value']:
            return []
        return [{'kind': 'question_total', 'value': value, 'label': literal,
                 'region': copy.deepcopy(region)}]
    except (KeyError, TypeError, ValueError, IndexError):
        return []
